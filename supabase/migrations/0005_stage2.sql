/* ---------------------------------------------------------------- order */

-- Every list shows rows in the order they were added (like the demo), so each table gets a running number.
do $$
declare t text;
begin
  foreach t in array array['universities', 'profiles', 'hostels', 'reviews', 'bookings', 'rooms', 'tenants', 'visitors', 'notices', 'invites', 'docs', 'flags', 'saved'] loop
    if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = t and column_name = 'seq') then
      execute format('alter table public.%I add column seq bigint generated by default as identity', t);
    end if;
  end loop;
end $$;

/* ---------------------------------------------------------------- room counts */

-- How many places of each room type are taken, worked out again from scratch.
-- A hostel with its rooms set up counts its ready beds, and the students who live there or are about to arrive.
-- A hostel without rooms counts its active bookings. Old, finished and cancelled bookings never count.
create or replace function public.recount_taken(hid text) returns void
language plpgsql security definer set search_path = public as $$
declare has_rooms boolean := exists (select 1 from rooms where hostel_id = hid);
begin
  update hostels h set rooms = coalesce((
    select jsonb_agg(jsonb_set(jsonb_set(v, '{total}', to_jsonb(c.total)), '{taken}', to_jsonb(least(c.total, c.taken))) order by i)
    from jsonb_array_elements(h.rooms) with ordinality x(v, i)
    cross join lateral (select
      case when has_rooms then (select coalesce(sum(r.beds), 0)::int from rooms r where r.hostel_id = hid and r.type = v->>'t' and r.status = 'ready')
        else coalesce((v->>'total')::int, 0) end as total,
      case when has_rooms then (select count(*)::int from tenants t where t.hostel_id = hid and t.status <> 'out' and t.type = v->>'t')
        else (select count(*)::int from bookings b where b.hostel_id = hid and b.room = v->>'t' and b.status in ('paid', 'checked-in')) end as taken) c
  ), '[]'::jsonb)
  where h.id = hid;
end $$;
revoke execute on function public.recount_taken(text) from public, anon, authenticated;

create or replace function public.count_taken() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op in ('UPDATE', 'DELETE') then perform recount_taken(old.hostel_id); end if;
  if tg_op in ('INSERT', 'UPDATE') and (tg_op = 'INSERT' or new.hostel_id is distinct from old.hostel_id) then perform recount_taken(new.hostel_id); end if;
  return null;
end $$;

drop trigger if exists count_taken on public.bookings;
create trigger count_taken after insert or delete or update of status, room, hostel_id on public.bookings for each row execute function public.count_taken();
drop trigger if exists count_taken on public.tenants;
create trigger count_taken after insert or delete or update of status, type, hostel_id on public.tenants for each row execute function public.count_taken();
drop trigger if exists count_taken on public.rooms;
create trigger count_taken after insert or delete or update of status, type, beds, hostel_id on public.rooms for each row execute function public.count_taken();

-- An owner who renames or adds a room type keeps the right count for it.
create or replace function public.recount_after_edit() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.rooms is distinct from old.rooms then perform recount_taken(new.id); end if;
  return null;
end $$;
drop trigger if exists recount_after_edit on public.hostels;
create trigger recount_after_edit after update of rooms on public.hostels for each row
  when (pg_trigger_depth() = 0) execute function public.recount_after_edit();

-- Fix the counts already in the database.
select public.recount_taken(id) from public.hostels;

/* ---------------------------------------------------------------- listing edits */

-- Same rules as before (0002), with two fixes:
-- a new hostel from an approved owner starts as "checked owner", and an owner who sends a listing
-- back for review clears the admin's old note, so it does not show again.
create or replace function public.guard_hostel() returns trigger
language plpgsql as $$
begin
  if not public.from_app() or public.is_admin() then return new; end if;
  if tg_op = 'INSERT' then
    new.status := 'draft'; new.rating := 0; new.n_rev := 0; new.views := 0; new.saves := 0;
    new.verified := exists (select 1 from profiles where id = new.owner_id and owner_status = 'approved');
    new.listed_at := null; new.paused_for := null; new.suspend_reason := null; new.review_note := null; new.review_sections := null;
    new.rooms := (select coalesce(jsonb_agg(jsonb_set(v, '{taken}', '0')), '[]'::jsonb) from jsonb_array_elements(new.rooms) v);
    return new;
  end if;
  if public.works_at(old.id) and not public.owns_hostel(old.id) then
    -- Custodians only update room counts when they take rooms in or out of use.
    if (to_jsonb(new) - 'rooms') is distinct from (to_jsonb(old) - 'rooms') then raise exception 'Custodians cannot edit the listing.'; end if;
  end if;
  if new.status = 'in_review' and old.status is distinct from 'in_review' then
    -- Sending it back for review: the owner may clear the admin's old note.
    if new.review_note is null then old.review_note := null; end if;
    if new.review_sections is null then old.review_sections := null; end if;
  end if;
  if new.owner_id is distinct from old.owner_id or new.verified is distinct from old.verified or new.rating is distinct from old.rating
     or new.n_rev is distinct from old.n_rev or new.paused_for is distinct from old.paused_for or new.suspend_reason is distinct from old.suspend_reason
     or new.review_note is distinct from old.review_note or new.review_sections is distinct from old.review_sections
     or new.listed_at is distinct from old.listed_at or new.created_at is distinct from old.created_at then
    raise exception 'Only the Nestly team can change that part of a listing.';
  end if;
  new.views := old.views; new.saves := old.saves;
  if new.status is distinct from old.status
     and not (new.status = 'in_review' and old.status in ('draft', 'changes_requested', 'live')) then
    raise exception 'Only the Nestly team can publish or pause a listing.';
  end if;
  -- Keep the server's booked counts for every room type that already existed.
  new.rooms := (
    select coalesce(jsonb_agg(case when o.v is null then n.v else jsonb_set(n.v, '{taken}', coalesce(o.v->'taken', '0')) end order by n.i), '[]'::jsonb)
    from jsonb_array_elements(new.rooms) with ordinality n(v, i)
    left join lateral (select v from jsonb_array_elements(old.rooms) v where v->>'t' = n.v->>'t' limit 1) o on true
  );
  return new;
end $$;

/* ---------------------------------------------------------------- messages to the Nestly team */

-- Owners and students cannot see who the admins are, so the database tells the admins itself.
create or replace function public.tell_admins(p_kind text, p_title text, p_text text, p_to text) returns void
language sql security definer set search_path = public as $$
  insert into notifications (user_id, kind, title, text, "to")
  select id, p_kind, p_title, p_text, p_to from profiles where role = 'admin' and not suspended;
$$;
revoke execute on function public.tell_admins(text, text, text, text) from public, anon, authenticated;

-- A listing sent for review, or a live listing whose name, photos or location changed.
create or replace function public.admins_hear_hostel() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'in_review' and old.status is distinct from 'in_review' then
    if old.status = 'live' then
      perform tell_admins('review', 'Listing changed', new.name || ' changed its name, photos or location.', '/a/reviews');
    else
      perform tell_admins('review', 'Listing waiting for review', new.name || ' by ' || new.owner_name || '.', '/a/reviews');
    end if;
  end if;
  return null;
end $$;
drop trigger if exists admins_hear_hostel on public.hostels;
create trigger admins_hear_hostel after update of status on public.hostels for each row execute function public.admins_hear_hostel();

-- A new owner who sent their details.
create or replace function public.admins_hear_owner() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.owner_status = 'pending' and old.owner_status is distinct from 'pending' then
    perform tell_admins('review', 'Owner waiting for review', new.name || ' sent their ID and payment account.', '/a/reviews');
  end if;
  return null;
end $$;
drop trigger if exists admins_hear_owner on public.profiles;
create trigger admins_hear_owner after update of owner_status on public.profiles for each row execute function public.admins_hear_owner();

-- A report from a student or owner.
create or replace function public.admins_hear_flag() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  perform tell_admins('flag', 'New report about ' || coalesce((select name from hostels where id = new.hostel_id), 'a hostel'),
    new.reason || ': ' || coalesce(nullif(new.text, ''), 'No details given.'), '/a/flags');
  return null;
end $$;
drop trigger if exists admins_hear_flag on public.flags;
create trigger admins_hear_flag after insert on public.flags for each row execute function public.admins_hear_flag();
